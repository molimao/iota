import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = new URL("../src/components/site/project-expansion/", import.meta.url);
const locales = ["zh", "zh-TW", "en", "ko", "ja"];
const rows = readdirSync(root)
  .filter((name) => name.endsWith(".json"))
  .sort()
  .flatMap((name) => {
    const pair = JSON.parse(readFileSync(new URL(name, root), "utf8"));
    if (!Array.isArray(pair) || pair.length !== 2)
      throw new Error(`${name}: expected two articles`);
    for (const row of pair) {
      if (`${row.project}.json` !== name || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(row.slug))
        throw new Error(`${name}: invalid identity`);
      for (const field of ["title", "answer", "checks", "example"])
        for (const locale of locales)
          if (typeof row[field]?.[locale] !== "string" || !row[field][locale].trim())
            throw new Error(`${row.slug}: missing ${field}/${locale}`);
      if (!row.sources?.length || row.sources.some((url) => new URL(url).protocol !== "https:"))
        throw new Error(`${row.slug}: invalid sources`);
    }
    return pair;
  });
if (new Set(rows.map((row) => row.slug)).size !== rows.length)
  throw new Error("Duplicate expansion slug");
const topic = {
  zh: "具体问题",
  "zh-TW": "具體問題",
  en: "Practical checks",
  ko: "상황별 확인",
  ja: "状況別の確認",
};
const metadata = rows.map((row) => ({
  slug: row.slug,
  project: row.project,
  published: "2026-10-26",
  modified: "2026-10-26",
  title: row.title,
  description: row.answer,
  summary: row.answer,
  topic,
  related: row.related,
  sources: row.sources.map((url) => ({ name: new URL(url).hostname, url })),
  body: Object.fromEntries(locales.map((locale) => [locale, []])),
}));
const output =
  '// Generated by scripts/generate-project-expansion.mjs.\nimport type { Article } from "../articles";\nexport const expansionMetadata: Article[] = ' +
  JSON.stringify(metadata, null, 2) +
  ";\n";
writeFileSync(fileURLToPath(new URL("metadata.ts", root)), output);
console.log(`Generated metadata for ${rows.length} project expansion articles.`);
