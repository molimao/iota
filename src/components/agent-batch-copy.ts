export function batchCopy(locale: SiteLocale) {
  const index = ["zh", "zh-TW", "en", "ko", "ja"].indexOf(locale);
  return Object.fromEntries(Object.entries(text).map(([k, v]) => [k, v[index]!])) as Record<
    keyof typeof text,
    string
  >;
}

export function batchConfirmation(copy: ReturnType<typeof batchCopy>, action: AgentBatch["action"], count: number) {
  return {
    start: copy.confirmStart,
    stop: copy.confirmStop,
    restart: copy.confirmRestart,
    update: copy.confirmUpdate,
  }[action].replace("{n}", String(count)).replace("{macs}", count === 1 ? "Mac" : "Macs");
}
