import type { Article } from "../articles";

type L = Record<"zh" | "zh-TW" | "en" | "ko" | "ja", string>;
type Q = NonNullable<Article["questions"]>;
type Table = NonNullable<Article["comparison"]>;

function t(zh: string, tw: string, en: string, ko: string, ja: string): L {
  return { zh, "zh-TW": tw, en, ko, ja };
}

function questions(rows: Array<[L, L]>): Q {
  const locales = ["zh", "zh-TW", "en", "ko", "ja"] as const;
  return Object.fromEntries(
    locales.map((locale) => [
      locale,
      rows.map(([question, answer]) => ({ question: question[locale], answer: answer[locale] })),
    ]),
  ) as Q;
}

function table(title: L, headers: L[], rows: L[][]): { comparisonTitle: L; comparison: Table } {
  const locales = ["zh", "zh-TW", "en", "ko", "ja"] as const;
  return {
    comparisonTitle: title,
    comparison: Object.fromEntries(
      locales.map((locale) => [
        locale,
        {
          headers: headers.map((header) => header[locale]),
          rows: rows.map((row) => row.map((cell) => cell[locale])),
        },
      ]),
    ) as Table,
  };
}

